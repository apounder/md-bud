class RunError(RuntimeError):
    pass


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def executable(config):
    binary = config["cpptraj"]
    path = shutil.which(binary)
    if path:
        return path
    if Path(binary).is_file():
        return str(Path(binary).resolve())
    raise RunError("CPPTRAJ was not found. Activate your AmberTools environment, or set cpptraj to its executable path in the configuration. On Windows, run the workflow and CPPTRAJ together inside WSL/Linux if using a Linux installation.")


def invoke(binary, args, cwd, log_path):
    """No shell; protect filenames from CPPTRAJ's argv and trajin re-parsing.

    CPPTRAJ joins argv and tokenizes it again; -y is subsequently parsed as a
    trajin expression as well. Relative, whitespace-free symlink names survive
    both passes. The process cwd stays unchanged, preserving output locations.
    """
    log_path = Path(log_path)
    log_path.parent.mkdir(parents=True, exist_ok=True)
    with ExitStack() as cleanup, log_path.open("w", encoding="utf-8") as log:
        native_args = list(map(str, args))
        aliases = None
        try:
            for i in range(1, len(native_args)):
                value = native_args[i]
                if args[i-1] in {"-p", "-y", "-i", "-c", "-d"} and any(c.isspace() or c in "\"'" for c in value):
                    if aliases is None:
                        aliases = Path(cleanup.enter_context(tempfile.TemporaryDirectory(prefix=".cpptraj-input-", dir=cwd)))
                    source = Path(value)
                    if not source.is_absolute():
                        source = Path(cwd) / source
                    source = source.resolve()
                    suffix = re.sub(r"[^A-Za-z0-9.]", "_", "".join(source.suffixes))
                    alias = aliases / f"input_{i}{suffix}"
                    try:
                        alias.symlink_to(source)
                    except OSError:
                        # Windows normally denies symlinks without Developer Mode.
                        # Hardlinks do not copy potentially huge trajectories.
                        if source.exists():
                            try:
                                alias.hardlink_to(source)
                            except OSError:
                                if source.suffix.lower() in {".in", ".prmtop", ".parm7", ".pdb", ".top", ".psf"} and source.stat().st_size <= 64 * 1024**2:
                                    shutil.copyfile(source, alias)
                                else:
                                    raise RunError("Could not create a whitespace-free input alias. Put analysis outputs on the same volume as trajectories, or use paths without spaces.")
                        # Keep a missing-file alias absent; native CPPTRAJ reports
                        # its normal reader error and the mapping remains logged.
                    native_args[i] = f"{aliases.name}/{alias.name}"
                    log.write(f"# Input alias: {native_args[i]} -> {source}\n")
                elif any(c.isspace() or c in "\"'" for c in value):
                    # Non-file arguments such as masks need only the argv pass.
                    native_args[i] = quote(value)
            log.flush()
            result = subprocess.run([binary, *native_args], cwd=cwd, stdout=log, stderr=subprocess.STDOUT, text=True, check=False)
        except OSError as exc:
            raise RunError(f"Could not execute CPPTRAJ or prepare input links: {exc}; see {log_path}") from exc
    text = log_path.read_text(encoding="utf-8", errors="replace")
    errors = re.findall(r"(?im)^\s*(?:Error:|Fatal:).*$", text)
    if result.returncode != 0 or errors:
        raise RunError(f"CPPTRAJ failed (exit {result.returncode}); see {log_path}. " + " ".join(errors[:3]))
    return text


def write_script(path, commands):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# Generated by MD-bud; exact commands retained for reproducibility.\n" + "\n".join(commands) + "\n", encoding="utf-8")


def execute_script(binary, commands, directory, stem, *, show_progress=True):
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{stem}.in"
    write_script(path, commands)
    with CalculationProgress(directory / f"{stem}.log", enabled=show_progress):
        return invoke(binary, ["-i", str(path)], directory, directory / f"{stem}.log")


def image_commands(config):
    if config["imaging"]["mode"] == "off":
        return []
    anchor = config["imaging"].get("anchor")
    return ["autoimage" + (" anchor " + quote(anchor) if anchor else "")]


def select_windows(lengths, frames):
    """Select frames over the joined segments of ONE replica, preserving stride."""
    start, stop, stride = frames["start"], frames["stop"], frames["stride"]
    total = sum(lengths)
    if start > total:
        raise RunError(f"Selection starts at {start}, but replica has only {total} frames.")
    if stop == -1:
        stop = total
    elif stop > total:
        raise RunError(f"Selection stops at {stop}, but replica has only {total} frames. Use -1 for all remaining frames.")
    offset = 0
    windows = []
    for length in lengths:
        low, high = max(start, offset + 1), min(stop, offset + length)
        first = low + (start - low) % stride
        if first <= high:
            last = first + ((high - first) // stride) * stride
            windows.append({"start": first - offset, "stop": last - offset, "stride": stride,
                            "offset": offset, "count": (last - first) // stride + 1})
        else:
            windows.append(None)
        offset += length
    return windows


def trajin_commands(replica):
    return [f"trajin {quote(path)} {window['start']} {window['stop']} {window['stride']}"
            for path, window in zip(replica["trajectories"], replica["windows"]) if window]


def _fingerprint(path, hash_file=False):
    path = Path(path)
    stat = path.stat()
    result = {"path": str(path), "size_bytes": stat.st_size, "mtime_ns": stat.st_mtime_ns}
    if hash_file:
        digest = hashlib.sha256()
        with path.open("rb") as handle:
            for block in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(block)
        result["sha256"] = digest.hexdigest()
    return result


def _prepare(config, output, require_empty=True):
    output = Path(output)
    if require_empty and output.exists() and any(output.iterdir()):
        raise RunError(f"Results directory is not empty: {output}. Choose a new --output to avoid mixing or overwriting runs.")
    selections, info = resolve_selections(config)
    batches = build_batches(config, selections)
    pooled = build_pooled_batches(config, selections)
    if not batches and not pooled:
        raise RunError("No applicable analyses selected. Check selections and analysis.enabled.")
    output.mkdir(parents=True, exist_ok=True)
    save_config(config, output / "resolved_config.json")
    save_config(info, output / "topology_inspection.json")
    with (output / "residue_map.dat").open("w", encoding="utf-8") as handle:
        handle.write("#topology_residue\tname\tclassification\tatoms\n")
        for residue in info["residues"]:
            handle.write(f"{residue['index']}\t{residue['name']}\t{residue['kind']}\t{','.join(residue['atoms'])}\n")
    plan = {"per_replica": batches, "pooled": pooled, "selections": selections,
            "replicas": config["replicas"], "warnings": info["warnings"]}
    save_config(plan, output / "plan.json")
    return selections, info, batches, pooled


